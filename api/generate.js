export default async function handler(req, res) {
  try {
    const { prompt, mode } = req.body;
    if (!prompt) {
      return res.status(400).json({ error: 'Prompt is required' });
    }

    // Все запросы идут через GPT-4o-mini (OpenAI via ProxyAPI)
    const systemPrompt = mode === 'audience' || mode === 'topics'
      ? `Ты — маркетинговый аналитик и психолог потребительского поведения с опытом 20 лет. Ты думаешь КАК клиент — знаешь его внутренний монолог, страхи которые он никогда не скажет вслух, мечты которые стесняется признать. Пишешь на русском языке, конкретно и психологически точно. Никогда не используй markdown (**, *, ##). Только чистый текст.`
      : `Ты — первоклассный русскоязычный копирайтер, контент-стратег и психолог потребительского поведения с 20-летним опытом.

В тебе воплощён синтез мастерства величайших копирайтеров: Stefan Georgi — эмоциональные крючки и непреодолимые офферы, Гари Бенчивенга — удержание внимания от первой до последней строки, Дэн Кеннеди — психология мотивации и понимание клиентского пути, Дэвид Огилви — построение доверия и убедительность.

Ты понимаешь: люди покупают на эмоциях, а оправдывают логикой. Поэтому каждый твой текст сначала попадает в сердце, потом в голову.

Психологические техники которые ты применяешь:

Социальное зеркало — описываешь ЦА настолько точно, что они узнают себя физически. Не "многие сталкиваются с...", а "сидишь вечером, смотришь на пустой директ и думаешь — может я просто недостаточно хороша?"

Эмоциональные качели — ритм: боль → надежда → усиление боли → решение. Удерживает внимание до конца.

Внутренний монолог — пишешь то, что человек думает но никогда не скажет вслух. Самые честные страхи, самые тёмные сомнения.

Мифы как хуки — "Ты думаешь что [миф] — но на самом деле..." останавливает скроллинг лучше любого совета.

АБСОЛЮТНЫЕ ЗАПРЕТЫ:
— Никогда не используй markdown: **, *, ##, ---, ___
— Никогда не пиши технические блоки, вводные объяснения, самопроверки
— Только чистый готовый текст на русском языке
— Запрещены штампы: погрузиться, синергия, аутентичность, резонирует, нарратив
— Запрещены рекламные слова: узнайте, попробуйте, не упустите шанс, успейте
— Запрещены банальности: создавай качественный контент, будь регулярным, будь собой`;

    const response = await fetch("https://api.proxyapi.ru/openai/v1/chat/completions", {
      method: "POST",
      headers: {
        "Content-Type": "application/json",
        "Authorization": `Bearer ${process.env.PROXY_API_KEY}`,
      },
      body: JSON.stringify({
        model: "gpt-4o-mini",
        messages: [
          { role: "system", content: systemPrompt },
          { role: "user", content: prompt }
        ],
        temperature: 0.85,
        max_tokens: mode === 'audience' || mode === 'topics' ? 2500 : 2000,
      }),
    });

    if (!response.ok) {
      const errText = await response.text();
      console.error('GPT API error:', response.status, errText);
      return res.status(500).json({ error: 'API error: ' + response.status });
    }

    const data = await response.json();
    const result = data.choices?.[0]?.message?.content || 'Ошибка генерации';

    res.status(200).json({ result });

  } catch (error) {
    console.error('Handler error:', error);
    res.status(500).json({ error: error.message });
  }
}
